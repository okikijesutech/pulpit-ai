import { SuggestionCandidate } from '@pulpit-ai/shared-types';

export interface CandidateRegistryEntry {
  candidate: SuggestionCandidate;
  registeredAt: number;
  expiresAt: number;
  used: boolean;
  usedAt?: number;
}

export interface CandidateRegistryOptions {
  /** Time-to-live for a candidate in milliseconds (default: 120,000ms = 2 minutes) */
  ttlMs?: number;
}

export interface ConsumeCandidateResult {
  success: boolean;
  candidate?: SuggestionCandidate;
  reason?: string;
  code?: 'UNKNOWN_OR_FORGED' | 'REPLAY' | 'EXPIRED';
}

export class CandidateRegistry {
  private readonly entries = new Map<string, CandidateRegistryEntry>();
  private readonly ttlMs: number;

  constructor(options: CandidateRegistryOptions = {}) {
    this.ttlMs = options.ttlMs ?? 120_000; // 2 minutes expiry
  }

  /**
   * Registers a suggestion candidate generated by an AI generator.
   */
  public registerCandidate(candidate: SuggestionCandidate, registeredAt = Date.now()): void {
    if (!candidate || !candidate.id) {
      return;
    }

    this.entries.set(candidate.id, {
      candidate,
      registeredAt,
      expiresAt: registeredAt + this.ttlMs,
      used: false
    });

    this.prune(registeredAt);
  }

  /**
   * Retrieves a candidate entry by ID without consuming it.
   */
  public getCandidate(candidateId: string): Readonly<CandidateRegistryEntry> | undefined {
    return this.entries.get(candidateId);
  }

  /**
   * Consumes a candidate for single-use approval.
   * Enforces:
   * 1. Must exist in registry (blocks forged payloads / unknown IDs).
   * 2. Must not be already used (blocks replay attacks).
   * 3. Must not have exceeded its 2-minute expiration window.
   */
  public consumeCandidate(candidateId: string, now = Date.now()): ConsumeCandidateResult {
    if (!candidateId || typeof candidateId !== 'string') {
      return {
        success: false,
        reason: 'Approval rejected: Forged or invalid candidate ID format.',
        code: 'UNKNOWN_OR_FORGED'
      };
    }

    const entry = this.entries.get(candidateId);
    if (!entry) {
      return {
        success: false,
        reason: `Unknown candidate ID '${candidateId}' (forged payload or un-registered ID rejected).`,
        code: 'UNKNOWN_OR_FORGED'
      };
    }

    if (entry.used) {
      return {
        success: false,
        reason: `Candidate '${candidateId}' has already been approved (replay rejected). Approvals are single-use only.`,
        code: 'REPLAY'
      };
    }

    if (now > entry.expiresAt) {
      return {
        success: false,
        reason: `Candidate suggestion '${candidateId}' has expired (exceeded 2-minute validity window).`,
        code: 'EXPIRED'
      };
    }

    // Mark as consumed (single-use)
    entry.used = true;
    entry.usedAt = now;
    entry.candidate.status = 'approved';

    return {
      success: true,
      candidate: entry.candidate
    };
  }

  /**
   * Cleans up expired entries older than 2x the TTL to prevent unbounded memory growth.
   */
  public prune(now = Date.now()): void {
    const cutoff = now - this.ttlMs * 2;
    for (const [id, entry] of this.entries.entries()) {
      if (entry.expiresAt < cutoff) {
        this.entries.delete(id);
      }
    }
  }

  /**
   * Resets the registry (useful for testing).
   */
  public clear(): void {
    this.entries.clear();
  }
}
